-- Things to do / ideas within a travel trip.
-- Run once in Supabase SQL Editor (after ha_travel.sql).

create table if not exists ha_trip_ideas (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references ha_trips(id) on delete cascade,
  location_id bigint references ha_trip_locations(id) on delete cascade,
  title text not null,
  category text not null default 'other' check (category in (
    'restaurant', 'activity', 'museum_gallery', 'sightseeing',
    'nature', 'shopping', 'family', 'nightlife', 'other'
  )),
  link text,
  map_link text,
  suggested_by text,
  notes text,
  status text not null default 'suggested' check (status in (
    'suggested', 'want_to_do', 'booked', 'done', 'skip'
  )),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

comment on table ha_trip_ideas is 'Suggested restaurants, activities, museums etc. for a trip or location.';
comment on column ha_trip_ideas.suggested_by is 'Who recommended this (friend, guide, blog…).';

create index if not exists idx_ha_trip_ideas_trip on ha_trip_ideas(trip_id, sort_order);
create index if not exists idx_ha_trip_ideas_location on ha_trip_ideas(location_id);
create index if not exists idx_ha_trip_ideas_category on ha_trip_ideas(category);

alter table ha_trip_ideas enable row level security;
drop policy if exists "Public read ha_trip_ideas" on ha_trip_ideas;
drop policy if exists "Public write ha_trip_ideas" on ha_trip_ideas;
create policy "Public read ha_trip_ideas" on ha_trip_ideas for select using (true);
create policy "Public write ha_trip_ideas" on ha_trip_ideas for all using (true) with check (true);

notify pgrst, 'reload schema';
