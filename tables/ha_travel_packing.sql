-- Per-trip packing lists (hand luggage vs suitcase, packed or not).
-- Run once in Supabase SQL Editor.

create table if not exists ha_trip_packing_items (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references ha_trips(id) on delete cascade,
  name text not null,
  bag text not null default 'suitcase' check (bag in ('hand_luggage', 'suitcase')),
  packed boolean not null default false,
  person text not null default 'shared' check (person in ('shared', 'conor', 'cian', 'rebecca')),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

comment on table ha_trip_packing_items is 'Packing checklist items for a trip.';

create index if not exists idx_ha_trip_packing_trip on ha_trip_packing_items(trip_id, sort_order, id);

alter table ha_trip_packing_items enable row level security;

drop policy if exists "Public read ha_trip_packing_items" on ha_trip_packing_items;
drop policy if exists "Public write ha_trip_packing_items" on ha_trip_packing_items;
create policy "Public read ha_trip_packing_items" on ha_trip_packing_items for select using (true);
create policy "Public write ha_trip_packing_items" on ha_trip_packing_items for all using (true) with check (true);

notify pgrst, 'reload schema';
