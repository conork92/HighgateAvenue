-- Travel: trips, locations within trips, and stay options (hotels / Airbnbs).
-- Run once in Supabase SQL Editor.

create table if not exists ha_trips (
  id bigint generated by default as identity primary key,
  title text not null,
  start_date date,
  end_date date,
  notes text,
  status text not null default 'planning' check (status in ('planning', 'booked', 'completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists ha_trip_locations (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references ha_trips(id) on delete cascade,
  name text not null,
  start_date date,
  end_date date,
  notes text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists ha_trip_stays (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references ha_trips(id) on delete cascade,
  location_id bigint references ha_trip_locations(id) on delete cascade,
  location_name text,
  title text not null,
  link text,
  image_url text,
  stay_type text default 'other' check (stay_type in ('hotel', 'airbnb', 'b_and_b', 'hostel', 'other')),
  price text,
  check_in_date date,
  check_out_date date,
  pros text,
  cons text,
  notes text,
  status text not null default 'considering' check (status in ('considering', 'shortlist', 'rejected', 'booked')),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

comment on table ha_trips is 'Top-level travel trips (e.g. Ireland summer).';
comment on table ha_trip_locations is 'Stops/regions within a trip (e.g. Kerry, Cork).';
comment on table ha_trip_stays is 'Hotel/Airbnb options to compare for a trip or location.';

create index if not exists idx_ha_trips_start_date on ha_trips(start_date desc);
create index if not exists idx_ha_trip_locations_trip on ha_trip_locations(trip_id, sort_order);
create index if not exists idx_ha_trip_stays_trip on ha_trip_stays(trip_id, sort_order);
create index if not exists idx_ha_trip_stays_location on ha_trip_stays(location_id);

alter table ha_trips enable row level security;
alter table ha_trip_locations enable row level security;
alter table ha_trip_stays enable row level security;

drop policy if exists "Public read ha_trips" on ha_trips;
drop policy if exists "Public write ha_trips" on ha_trips;
create policy "Public read ha_trips" on ha_trips for select using (true);
create policy "Public write ha_trips" on ha_trips for all using (true) with check (true);

drop policy if exists "Public read ha_trip_locations" on ha_trip_locations;
drop policy if exists "Public write ha_trip_locations" on ha_trip_locations;
create policy "Public read ha_trip_locations" on ha_trip_locations for select using (true);
create policy "Public write ha_trip_locations" on ha_trip_locations for all using (true) with check (true);

drop policy if exists "Public read ha_trip_stays" on ha_trip_stays;
drop policy if exists "Public write ha_trip_stays" on ha_trip_stays;
create policy "Public read ha_trip_stays" on ha_trip_stays for select using (true);
create policy "Public write ha_trip_stays" on ha_trip_stays for all using (true) with check (true);

